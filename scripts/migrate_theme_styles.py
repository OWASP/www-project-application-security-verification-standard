"""Regenerate module-based styles from a checkout of the pinned Just the Docs theme.

Usage: python scripts/migrate_theme_styles.py /path/to/just-the-docs
No Node.js or migration tools are needed to build or preview the site.
"""
from pathlib import Path
import re
import sys

THEME_REVISION = '2ed4c0af735e95af5c0dcf7a605b07d903005b4e'
ROOT = Path(__file__).resolve().parent.parent


def flatten(source, relative):
    path = source / relative
    text = path.read_text(encoding='utf-8')

    def expand(match):
        name = match[1]
        for base in (path.parent, source / '_sass'):
            candidate = base / name
            for target in (Path(str(candidate) + '.scss'), candidate.parent / ('_' + candidate.name + '.scss')):
                if target.is_file():
                    return flatten(source, target.relative_to(source))
        raise FileNotFoundError(f'{path}: {name}')

    return f'\n// Source: {relative}\n' + re.sub(r'@import\s+"([^"]+)"\s*;', expand, text)


def modernize(text):
    # Expand the legacy import graph into a single module. This preserves its
    # shared variable scope and stylesheet order, including dark-scheme overrides.
    for old, new in [('map-get', 'map.get'), ('map-keys', 'map.keys'),
                     ('length', 'list.length'), ('variable-exists', 'meta.variable-exists')]:
        text = re.sub(r'(?<![\w.-])' + old + r'\(', new + '(', text)

    # Legacy lighten/darken adjust HSL lightness by an absolute percentage.
    # color.adjust preserves that behavior; color.scale would change the colors.
    pattern = re.compile(r'\b(darken|lighten)\(([^(),]+),\s*([^(),]+)\)')
    text = pattern.sub(lambda m: 'color.adjust(' + m[2] + ', $lightness: ' +
                       ('-' if m[1] == 'darken' else '') + m[3].strip() + ', $space: hsl)', text)
    if re.search(r'\b(?:darken|lighten)\(', text):
        raise ValueError('Unconverted color function: review nested arguments')
    return text


def generate(source):
    destination = ROOT / '_sass/asvs'
    destination.mkdir(parents=True, exist_ok=True)
    for scheme in ('light', 'dark'):
        parts = ['_sass/support/support.scss', '_sass/custom/setup.scss', '_sass/color_schemes/light.scss']
        if scheme == 'dark':
            parts.append('_sass/color_schemes/dark.scss')
        parts.append('_sass/modules.scss')
        text = '\n'.join(flatten(source, p) for p in parts)
        header = f'// Generated by scripts/migrate_theme_styles.py.\n// Just the Docs {THEME_REVISION}; MIT license in LICENSE.txt.\n'
        imports = '\n'.join(f'@use "sass:{name}";' for name in ('color', 'map', 'list', 'meta'))
        (destination / (scheme + '.scss')).write_text(header + imports + '\n$logo: null !default;\n' + modernize(text), encoding='utf-8')
    (destination / 'LICENSE.txt').write_text((source / 'LICENSE.txt').read_text(encoding='utf-8'), encoding='utf-8')


if __name__ == '__main__':
    generate(Path(sys.argv[1]).resolve())
